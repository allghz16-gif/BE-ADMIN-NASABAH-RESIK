CREATE TABLE nasabah (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NULL,
  nama VARCHAR(100) NOT NULL,
  nik CHAR(16) NOT NULL,
  telepon VARCHAR(20) NOT NULL,
  email VARCHAR(150) NULL,
  jenis_kelamin ENUM('laki-laki', 'perempuan') NULL,
  tanggal_lahir DATE NULL,
  alamat TEXT NOT NULL,
  kota VARCHAR(100) NULL,
  kecamatan VARCHAR(100) NULL,
  kode_pos VARCHAR(10) NULL,
  foto VARCHAR(255) NULL,
  catatan TEXT NULL,
  status ENUM('aktif', 'nonaktif') NOT NULL DEFAULT 'aktif',
  tier ENUM('reguler', 'platinum') NOT NULL DEFAULT 'reguler',
  saldo DECIMAL(15,2) NOT NULL DEFAULT 0,
  poin INT UNSIGNED NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_nasabah_nik (nik),
  UNIQUE KEY uq_nasabah_email (email),
  KEY idx_nasabah_nama (nama),
  KEY idx_nasabah_telepon (telepon),
  KEY idx_nasabah_status (status),
  CONSTRAINT fk_nasabah_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;